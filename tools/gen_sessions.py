#!/usr/bin/env python3
"""Compose tls_client/sessions.py from the native signature plus templates.

The literal Session.__init__ parameter list must not be hand-written: it has to
agree with tls_client._core.Session, with the property surface generated by
tools/gen_requests_surface.py, and with the per-request overrides.  Generating
it from the native signature is what keeps the three in step.

Usage::

    python3 tools/gen_sessions.py            # write tls_client/sessions.py
    python3 tools/gen_sessions.py --check    # fail when the file is stale (CI)
"""

import argparse
import inspect
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tls_client._core import Session as NativeSession

HEADER_PATH = ROOT / "tools" / "_sessions_header.py"
BODY_PATH = ROOT / "tools" / "_sessions_body.py"


def _render(annotation) -> str:
    if annotation is inspect.Parameter.empty:
        return "Any"
    if isinstance(annotation, str):
        return annotation
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Literal:
        # ClientIdentifiers is a Literal alias of the supported profile names.
        return "ClientIdentifiers"
    if origin is typing.Union:
        nn = [a for a in args if a is not type(None)]
        inner = ", ".join(_render(a) for a in nn)
        return "Optional[%s]" % inner if len(nn) == 1 else "Union[%s]" % inner
    if origin is list:
        return "List[%s]" % ", ".join(_render(a) for a in args)
    if origin is dict:
        return "Dict[%s]" % ", ".join(_render(a) for a in args)
    if origin is tuple:
        return "Tuple[%s]" % ", ".join(_render(a) for a in args)
    if annotation is typing.Any:
        return "Any"
    return getattr(annotation, "__name__", repr(annotation))


def _default(param) -> str:
    if param.default is inspect.Parameter.empty:
        return "None"
    return repr(param.default)


def _normalize_optional(annotation: str, default: str) -> str:
    """Spell "may be None" explicitly, so the signature is PEP 484 complete.

    The native annotations write Union[X, Y] = None for several proxy/cert
    options; widening them to Optional[Union[X, Y]] keeps type checkers and
    ruff (RUF013) happy without changing runtime behaviour.
    """
    if default != "None" or annotation in ("Any", "None"):
        return annotation
    if annotation.startswith("Optional["):
        return annotation
    if annotation.startswith("Union[") or annotation.count(",") == 0:
        return "Optional[%s]" % annotation
    return "Optional[Union[%s]]" % annotation


def build() -> str:
    """Return the full text tls_client/sessions.py should have."""
    signature = inspect.signature(NativeSession.__init__)
    lines = []
    for name, param in signature.parameters.items():
        if name == "self" or param.kind is not param.KEYWORD_ONLY:
            continue
        annotation = _render(param.annotation)
        default = _default(param)
        lines.append(
            "        %s: %s = %s,"
            % (name, _normalize_optional(annotation, default), default)
        )
    # requests-only keywords the facade adds on top of the native signature.
    lines.extend(
        (
            "",
            "        # -- requests.Session extras ----------------------------------",
            "        hooks: Optional[Dict[str, Any]] = None,",
            "        max_redirects: int = DEFAULT_REDIRECT_LIMIT,",
            "        trust_env: bool = True,",
        )
    )
    template = HEADER_PATH.read_text(encoding="utf-8") + BODY_PATH.read_text(
        encoding="utf-8"
    )
    return template.replace("__INIT_PARAMS__", "\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when stale")
    args = parser.parse_args()

    target = ROOT / "tls_client" / "sessions.py"
    generated = build()
    if args.check:
        try:
            current = target.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = ""
        if current != generated:
            sys.stderr.write(
                "%s is stale; run python3 tools/gen_sessions.py\n" % target
            )
            return 1
        print("%s is current" % target.name)
        return 0

    target.write_text(generated, encoding="utf-8")
    print("wrote %s (%d bytes)" % (target, len(generated)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
