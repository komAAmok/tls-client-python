// TestCapturedChromeProfilesRegistered verifies the generated table covers the
// whole captured range and that every version is selectable by name.
func TestCapturedChromeProfilesRegistered(t *testing.T) {
	majors := CapturedChromeMajors()
	if len(majors) == 0 {
		t.Fatal("captured profile table is empty")
	}

	const fullCount = 55
	if len(majors) == fullCount {
		if majors[0] != 99 || majors[len(majors)-1] != 153 {
			t.Fatalf("unexpected range %d..%d", majors[0], majors[len(majors)-1])
		}
	} else {
		t.Logf("trimmed table: %d majors (%d..%d)", len(majors), majors[0], majors[len(majors)-1])
		for _, major := range majors {
			if _, ok := expectedJA3[major]; !ok {
				t.Errorf("trimmed table contains major %d outside the captured range", major)
			}
		}
	}

	for _, major := range majors {
		name := fmt.Sprintf("chrome_%d", major)
		if _, ok := MappedTLSClients[name]; !ok {
			t.Errorf("profile %s is not registered", name)
		}
	}
}

// TestCapturedChromeSpecMatchesJA3 is the byte-level guard: it rebuilds the
// JA3 string from each generated ClientHello spec and compares it against the
// wire capture.  GREASE entries are dropped from both sides, matching JA3.
//
// Every major present in the generated table is checked.
func TestCapturedChromeSpecMatchesJA3(t *testing.T) {
	present := make(map[int]bool, len(chromeCapturedMajors))
	for _, major := range chromeCapturedMajors {
		present[major] = true
	}

	checked := 0
	for major, want := range expectedJA3 {
		if !present[major] {
			continue
		}
		major, want := major, want
		checked++
		t.Run(strconv.Itoa(major), func(t *testing.T) {
			spec, err := chromeCapturedSpec(major)
			if err != nil {
				t.Fatalf("spec: %v", err)
			}

			got := ja3FromSpec(spec)
			if got != want {
				t.Errorf("JA3 mismatch for chrome_%d\n got: %s\nwant: %s", major, got, want)
			}
			if gh, wh := md5Sum(got), md5Sum(want); gh != wh {
				t.Errorf("JA3 hash mismatch for chrome_%d: got %s want %s", major, gh, wh)
			}
		})
	}

	if checked == 0 {
		t.Fatal("no captured major was verified — the table and expectedJA3 do not overlap")
	}
}

// ja3FromSpec renders a ClientHelloSpec to a JA3 string.
func ja3FromSpec(spec tls.ClientHelloSpec) string {
	ciphers := make([]string, 0, len(spec.CipherSuites))
	for _, c := range spec.CipherSuites {
		if isGREASE(c) {
			continue
		}
		ciphers = append(ciphers, strconv.Itoa(int(c)))
	}

	exts := make([]string, 0, len(spec.Extensions))
	var curves []string
	for _, ext := range spec.Extensions {
		id, grease := extensionID(ext)
		if grease {
			continue
		}
		exts = append(exts, strconv.Itoa(int(id)))

		if sc, ok := ext.(*tls.SupportedCurvesExtension); ok && curves == nil {
			for _, c := range sc.Curves {
				if isGREASE(uint16(c)) {
					continue
				}
				curves = append(curves, strconv.Itoa(int(c)))
			}
		}
	}

	return "771," + strings.Join(ciphers, "-") + "," +
		strings.Join(exts, "-") + "," + strings.Join(curves, "-") + ",0"
}

func isGREASE(v uint16) bool {
	return v&0x0f0f == 0x0a0a
}

// extensionID recovers the wire id of a uTLS extension.  uTLS does not expose
// a common Id() method, so we map the types that appear in Chrome captures.
// The bool reports a GREASE extension, which JA3 excludes.
func extensionID(ext tls.TLSExtension) (uint16, bool) {
	switch e := ext.(type) {
	case *tls.SNIExtension:
		return 0, false
	case *tls.StatusRequestExtension:
		return 5, false
	case *tls.SupportedCurvesExtension:
		return 10, false
	case *tls.SupportedPointsExtension:
		return 11, false
	case *tls.SignatureAlgorithmsExtension:
		return 13, false
	case *tls.ALPNExtension:
		return 16, false
	case *tls.SCTExtension:
		return 18, false
	case *tls.UtlsPaddingExtension:
		return 21, false
	case *tls.ExtendedMasterSecretExtension:
		return 23, false
	case *tls.UtlsCompressCertExtension:
		return 27, false
	case *tls.FakeRecordSizeLimitExtension:
		return 28, false
	case *tls.SessionTicketExtension:
		return 35, false
	case *tls.SupportedVersionsExtension:
		return 43, false
	case *tls.PSKKeyExchangeModesExtension:
		return 45, false
	case *tls.KeyShareExtension:
		return 51, false
	case *tls.RenegotiationInfoExtension:
		return 65281, false
	case *tls.ApplicationSettingsExtension:
		return 17513, false
	case *tls.ApplicationSettingsExtensionNew:
		return 17613, false
	case *tls.GREASEEncryptedClientHelloExtension:
		return 65037, false
	case *tls.GenericExtension:
		return e.Id, false
	case *tls.UtlsGREASEExtension:
		return 0, true
	}
	if e, ok := ext.(interface{ ExtensionID() uint16 }); ok {
		return e.ExtensionID(), false
	}
	return 0, false
}

func md5Sum(s string) string {
	sum := md5.Sum([]byte(s))
	return hex.EncodeToString(sum[:])
}
